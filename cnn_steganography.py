
"""HybridShield: CNN-assisted block steganography.

No trained weights or dataset required.
Payload is encoded using luminance ordering of adjacent 4x4 blocks.
Save and upload the generated PNG without modifying it.
"""

import struct

import numpy as np
import torch
from torch import nn
from PIL import Image

BLOCK = 4
LOW = 65.0
HIGH = 190.0


class CNNBlockDecoder(nn.Module):
    """Fixed convolutional average-pooling layer."""
    def __init__(self):
        super().__init__()
        self.pool = nn.Conv2d(
            1, 1, kernel_size=BLOCK, stride=BLOCK, bias=False
        )
        with torch.no_grad():
            self.pool.weight.fill_(1.0 / (BLOCK * BLOCK))
        self.pool.weight.requires_grad_(False)

    def forward(self, image):
        return self.pool(image)


_DECODER = CNNBlockDecoder().eval()


def _bits(data):
    return "".join(f"{b:08b}" for b in data)


def _bytes(bits):
    return bytes(
        int(bits[i:i + 8], 2)
        for i in range(0, len(bits), 8)
    )


def _luminance(block):
    return (
        0.299 * block[:, :, 0]
        + 0.587 * block[:, :, 1]
        + 0.114 * block[:, :, 2]
    )


def embed_cnn_payload(image_path, output_path, payload):
    """Embed bytes into an image and save the result as PNG."""
    with Image.open(image_path) as im:
        arr = np.asarray(im.convert("RGB"), dtype=np.uint8).copy()

    h, w, _ = arr.shape
    h -= h % BLOCK
    w -= w % BLOCK

    pairs_per_row = (w // BLOCK) // 2
    capacity_bits = (h // BLOCK) * pairs_per_row

    # 4-byte payload length prefix.
    framed = struct.pack(">I", len(payload)) + payload
    bitstream = _bits(framed)

    if len(bitstream) > capacity_bits:
        max_payload = max(0, (capacity_bits - 32) // 8)
        raise ValueError(
            f"Image capacity too small. "
            f"Payload: {len(payload)} bytes; "
            f"approximate maximum: {max_payload} bytes. "
            f"Please use a larger image."
        )

    idx = 0

    for by in range(0, h, BLOCK):
        for pair in range(pairs_per_row):
            if idx >= len(bitstream):
                break

            x1 = pair * 2 * BLOCK
            x2 = x1 + BLOCK

            b1 = arr[by:by + BLOCK, x1:x1 + BLOCK].astype(np.float32)
            b2 = arr[by:by + BLOCK, x2:x2 + BLOCK].astype(np.float32)

            y1 = float(np.mean(_luminance(b1)))
            y2 = float(np.mean(_luminance(b2)))

            bit = bitstream[idx]
            idx += 1

            if bit == "1":
                targets = (HIGH, LOW)
            else:
                targets = (LOW, HIGH)

            for x, block, y, target in (
                (x1, b1, y1, targets[0]),
                (x2, b2, y2, targets[1]),
            ):
                shifted = np.clip(block + (target - y), 0, 255)
                current_y = float(np.mean(_luminance(shifted)))

                if abs(current_y - target) > 3:
                    shifted[:, :, :] = np.uint8(round(target))

                arr[by:by + BLOCK, x:x + BLOCK] = (
                    np.rint(shifted).astype(np.uint8)
                )

    Image.fromarray(arr, "RGB").save(output_path, format="PNG")


def extract_cnn_payload(image_path):
    """Extract embedded bytes from the original generated PNG."""
    with Image.open(image_path) as im:
        arr = np.asarray(im.convert("RGB"), dtype=np.uint8)

    h, w, _ = arr.shape
    h -= h % BLOCK
    w -= w % BLOCK

    if h < BLOCK or w < 2 * BLOCK:
        raise ValueError("Image is too small to contain a payload.")

    gray = _luminance(arr[:h, :w]).astype(np.float32)
    tensor = torch.from_numpy(gray).unsqueeze(0).unsqueeze(0)

    with torch.no_grad():
        means = _DECODER(tensor)[0, 0].cpu().numpy()

    bits = []
    for row in means:
        for j in range(0, len(row) - 1, 2):
            bits.append("1" if row[j] > row[j + 1] else "0")

    if len(bits) < 32:
        raise ValueError("No embedded payload detected.")

    length = int("".join(bits[:32]), 2)
    end = 32 + length * 8

    if length <= 0 or end > len(bits):
        raise ValueError(
            "Invalid payload. Upload the original PNG generated by the sender."
        )

    return _bytes("".join(bits[32:end]))
